// mapGPUName maps the name shown in mesa into our gpu name.
func mapGPUName(mesaName string) (string, error) {
	var vmFamilyNameMap = map[string]string{
		"VIRTGL": "virtio",
		"SVGAII": "vmware",
		"SVGAv3": "vmware",
	}
	var intelFamilyNameMap = map[string]string{
		"ADL":      "alderlake",
		"APL":      "apollolake",
		"BDW":      "broadwell",
		"BSW":      "braswell",
		"BXT":      "broxton",
		"BYT":      "baytrail",
		"CFL":      "coffeelake",
		"CHV":      "braswell",
		"CML":      "cometlake",
		"CNL":      "cannonlake",
		"GLK":      "geminilake",
		"HSW":      "haswell",
		"ICL":      "icelake",
		"ILK":      "ironlake",
		"JSL":      "jasperlake",
		"IVB":      "ivybridge",
		"KBL":      "kabylake",
		"MTL":      "meteorlake",
		"Pineview": "pinetrail",
		"RPL":      "raptorlake",
		"SKL":      "skylake",
		"SNB":      "sandybridge",
		"TGL":      "tigerlake",
		"WHL":      "whiskeylake",
	}
	// We check vmFamilyNameMap first as TGL is contained in VIRTGL.
	for key, value := range vmFamilyNameMap {
		if strings.Contains(strings.ToLower(mesaName), strings.ToLower(key)) {
			return value, nil
		}
	}
	for key, value := range intelFamilyNameMap {
		if strings.Contains(strings.ToLower(mesaName), strings.ToLower(key)) {
			return value, nil
		}
	}
	return "", fmt.Errorf("No map for %s", mesaName)
}

type generateParams struct {
	OutPath          string
	CopyrightYear    string
	ConstantMappings map[string]string
	Library          string
	FuncName         string
}

func genConstant(params generateParams) error {
	const tmplStr = `// Copyright {{.CopyrightYear}} The ChromiumOS Authors
// Use of this source code is governed by a BSD-style license that can be
// found in the LICENSE file.

package main

// Code generated by gen/gen_intel_pci_ids_map.go. DO NOT EDIT.

// Run the following code to regenerate it.
// go run cmd/hardware_probe/gen/gen_intel_pci_ids_map.go --library={{.Library}} --output={{.OutPath}} --function={{.FuncName}}
// gofmt -w -d -s {{.OutPath}}

func {{.FuncName}}() map[string]string {
	return map[string]string{
{{range $key, $val := .ConstantMappings}}
		"{{$key}}": "{{$val}}",{{end}}
	}
}
`

	file, err := os.Create(params.OutPath)
	if err != nil {
		return errors.Wrap(err, "failed to create output file")
	}
	if err := template.Must(template.New("gen").Parse(tmplStr)).Execute(file, params); err != nil {
		return errors.Wrap(err, "failed to generate file to "+params.OutPath)
	}
	return nil
}

func main() {
	outPath := flag.String("output", "cmd/hardware_probe/intel_pci_ids.go", "Output file name")
	mesaPath := flag.String("mesa", "../../../../../../../third_party/mesa", "Path to the mesa repository")
	funcName := flag.String("function", "getIntelPCIIDMap", "Function name in the output go file")
	pciLibrariesPath := flag.String("library", "i915_pci_ids.h:iris_pci_ids.h", `Path to libraries under $mesa/include/pci_ids/.
Use ':' to split between multiple libraries`)
	flag.Parse()

	pciLibraries := strings.Split(*pciLibrariesPath, ":")
	idMap := map[string]string{}
	for _, pci_ids_h := range pciLibraries {
		b, err := os.ReadFile(*mesaPath + "/include/pci_ids/" + pci_ids_h)
		if err != nil {
			fmt.Printf("Failed to read the file: %q\n", err)
			continue
		}

		reg := regexp.MustCompile(`CHIPSET\((.*)\)`)
		for _, line := range strings.Split(string(b), "\n") {
			matches := reg.FindStringSubmatch(line)
			if matches == nil {
				continue
			}

			chipSetAttrs := strings.Split(matches[1], ",")
			if len(chipSetAttrs) < 3 {
				fmt.Printf("malformed line detected: %s\n", line)
				continue
			}

			for i, attr := range chipSetAttrs {
				chipSetAttrs[i] = strings.Replace(strings.TrimSpace(attr), "\"", "", -1)
			}
			id := strings.ToLower(chipSetAttrs[0])
			familyName, err := mapGPUName(chipSetAttrs[2])
			if err != nil {
				fmt.Printf("Can't find the gpu name (%s) in our map\n", chipSetAttrs[2])
				continue
			}
			idMap[id] = familyName
		}
	}

	if err := genConstant(generateParams{
		CopyrightYear:    "2022",
		OutPath:          *outPath,
		ConstantMappings: idMap,
		Library:          *pciLibrariesPath,
		FuncName:         *funcName,
	}); err != nil {
		fmt.Printf("Failed to generate file: %v\n", err)
	} else {
		fmt.Printf("Successfully write to file: %v\n", *outPath)
	}

}
